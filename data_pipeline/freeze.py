"""Step 9: freeze and release package.

    python -m data_pipeline.freeze [--allow_no_git]

Refuses to run unless: benchmark_name is set, audit/checks.json exists and passed, and (if a
previous FREEZE.json exists with different content) `version` was bumped.
Writes into release/:
  manifests/groups_<split>.jsonl, questions_<split>.jsonl, controls, crops_index.jsonl,
  backgrounds_index.jsonl, backgrounds_licenses.csv, heldout_pairings.json, split_assignment.json
  FREEZE.json   sha256 of every manifest and every rendered image, git commit, config, version
  STATS.md      tables: classes, cutouts/class, backgrounds/region, groups/split, rejections,
                human-audit pass rates
  DATASHEET.md  skeleton (Datasheets for Datasets headings)
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from .classes import CLASS_REGION, CLASSES, HELDOUT_CLASSES, REGIONS
from .splits import SPLITS
from .utils import (REPO_ROOT, Config, config_sha256, get_logger, load_config, read_jsonl,
                    sha256_file, write_json)


def git_info() -> dict:
    try:
        commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, text=True).strip()
        dirty = bool(subprocess.check_output(["git", "status", "--porcelain"], cwd=REPO_ROOT, text=True).strip())
        return {"commit": commit, "dirty": dirty}
    except Exception:  # noqa: BLE001
        return {"commit": None, "dirty": None}


def counts_by(path: Path, key: str) -> Counter:
    return Counter(r[key] for r in read_jsonl(path)) if path.exists() else Counter()


def jsonl_reason_counts(path: Path) -> Counter:
    return Counter(r["reason"] for r in read_jsonl(path)) if path.exists() else Counter()


def md_table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def stats_md(cfg: Config) -> tuple[str, dict]:
    crops = counts_by(cfg.path("crops_index"), "class")
    bgs = counts_by(cfg.path("backgrounds_index"), "region")
    groups = {s: len(read_jsonl(cfg.path("groups_dir") / f"{s}.jsonl")) for s in SPLITS
              if (cfg.path("groups_dir") / f"{s}.jsonl").exists()}
    crop_rej = jsonl_reason_counts(cfg.path("crops_rejections"))
    bg_rej = jsonl_reason_counts(cfg.path("backgrounds_rejections")) + \
        jsonl_reason_counts(cfg.path("backgrounds_dir") / "fetch_rejections.jsonl")
    hpath = cfg.path("audit_dir") / "human_audit_stats.json"
    human = json.load(open(hpath)) if hpath.exists() else {}
    qpath = cfg.path("crops_qwen_check")
    qacc = json.load(open(qpath))["accuracy"] if qpath.exists() else {}
    kept = sorted(crops)
    parts = [f"# {cfg['benchmark_name']} v{cfg['version']} — statistics\n",
             f"Classes kept: {len(kept)} / {len(CLASSES)} "
             f"({sum(c not in HELDOUT_CLASSES for c in kept)} seen, {sum(c in HELDOUT_CLASSES for c in kept)} held-out)\n",
             "## Cutouts per class\n",
             md_table(["class", "region", "held-out", "cutouts", "qwen crop-only acc"],
                      [[c, CLASS_REGION[c], c in HELDOUT_CLASSES, crops[c],
                        f"{qacc[c]:.2f}" if c in qacc else "n/a"] for c in sorted(CLASSES)]),
             "\n## Backgrounds per region\n",
             md_table(["region", "backgrounds"], [[r, bgs[r]] for r in REGIONS] + [["TOTAL", sum(bgs.values())]]),
             "\n## Groups per split\n",
             md_table(["split", "groups", "images", "cells"], [[s, n, 7 * n, 21 * n] for s, n in groups.items()]),
             "\n## Filter rejections\n",
             md_table(["stage", "reason", "count"],
                      [["crops", k, v] for k, v in sorted(crop_rej.items())] +
                      [["backgrounds", k, v] for k, v in sorted(bg_rej.items())]),
             "\n## Human audit\n",
             md_table(["kind", "pass", "n", "rate"],
                      [[k, v["pass"], v["n"], f"{v['rate']:.3f}" if v["rate"] is not None else "n/a"]
                       for k, v in sorted(human.items())]) if human else "_not yet collected_"]
    return "\n".join(parts) + "\n", {"crops": dict(crops), "backgrounds": dict(bgs), "groups": groups,
                                     "crop_rejections": dict(crop_rej), "bg_rejections": dict(bg_rej),
                                     "human_audit": human}


