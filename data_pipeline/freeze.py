def freeze(cfg: Config, allow_no_git: bool = False) -> dict:
    log = get_logger("freeze", cfg)
    if not cfg.get("benchmark_name"):
        raise SystemExit("config.benchmark_name is not set (open item)")
    chk = cfg.path("audit_dir") / "checks.json"
    if not chk.exists() or not json.load(open(chk)).get("passed"):
        raise SystemExit("audit checks missing or failing: run `python -m data_pipeline.audit checks --use_saved`")
    git = git_info()
    if git["commit"] is None and not allow_no_git:
        raise SystemExit("not a git repository: commit the pipeline code first (or --allow_no_git)")
    if git.get("dirty"):
        log.warning("git working tree is dirty; the recorded commit does not fully describe the code")

    rel = cfg.path("release_dir")
    man = rel / "manifests"
    man.mkdir(parents=True, exist_ok=True)
    copies = {
        "crops_index.jsonl": cfg.path("crops_index"),
        "backgrounds_index.jsonl": cfg.path("backgrounds_index"),
        "backgrounds_licenses.csv": cfg.path("backgrounds_licenses"),
        "heldout_pairings.json": cfg.path("heldout_pairings"),
        "split_assignment.json": cfg.path("splits_file"),
        "class_status.json": cfg.path("crops_dir") / "class_status.json",
        "qwen_class_check.json": cfg.path("crops_qwen_check"),
        "audit_checks.json": chk,
    }
    for s in SPLITS + ("controls",):
        copies[f"groups_{s}.jsonl"] = cfg.path("groups_dir") / f"{s}.jsonl"
        copies[f"questions_{s}.jsonl"] = cfg.path("questions_dir") / f"{s}.jsonl"
    manifest_hashes = {}
    for name, src in copies.items():
        if src.exists():
            shutil.copyfile(src, man / name)
            manifest_hashes[f"manifests/{name}"] = sha256_file(man / name)
        else:
            log.warning("missing manifest source %s", src)

    renders = cfg.path("renders_dir")
    image_hashes = {str(p.relative_to(renders)): sha256_file(p) for p in sorted(renders.rglob("*.png"))}
    n_expected = 7 * sum(cfg["splits"]["group_counts"].values())
    n_main = sum(1 for k in image_hashes if not k.startswith("controls/") and "_harmonized" not in k)
    if n_main != n_expected:
        raise SystemExit(f"{n_main} rendered main images, expected {n_expected}: render every split first")

    content_hash = __import__("hashlib").sha256(
        json.dumps([manifest_hashes, image_hashes], sort_keys=True).encode()).hexdigest()
    prev_path = rel / "FREEZE.json"
    if prev_path.exists():
        prev = json.load(open(prev_path))
        if prev["content_sha256"] != content_hash and prev["version"] == cfg["version"]:
            raise SystemExit(f"content changed since freeze of v{prev['version']}: bump `version` in config.yaml")

    clean_cfg = {k: v for k, v in cfg.items() if not k.startswith("_")}
    freeze_rec = {
        "benchmark_name": cfg["benchmark_name"], "version": cfg["version"],
        "frozen_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "git": git, "config": clean_cfg, "config_sha256": config_sha256(cfg),
        "content_sha256": content_hash, "manifests": manifest_hashes, "images": image_hashes,
    }
    write_json(prev_path, freeze_rec)
    md, stats = stats_md(cfg)
    (rel / "STATS.md").write_text(md)
    write_json(rel / "stats.json", stats)
    n_groups = sum(stats["groups"].values())
    (rel / "DATASHEET.md").write_text(DATASHEET.format(name=cfg["benchmark_name"], version=cfg["version"],
                                                       n_groups=n_groups))
    log.info("frozen %s v%s: %d manifests, %d images, content %s", cfg["benchmark_name"], cfg["version"],
             len(manifest_hashes), len(image_hashes), content_hash[:12])
    return freeze_rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config")
    ap.add_argument("--allow_no_git", action="store_true")
    args = ap.parse_args()
    freeze(load_config(args.config), args.allow_no_git)


if __name__ == "__main__":
    main()
